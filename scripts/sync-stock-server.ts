// Bundle the same pure stock rules used by the browser for the edge runtime.
// Run whenever stock rules or historical sources change.
const result = await Bun.build({
  entrypoints: ['src/lib/socialMarket.ts'], target: 'browser', format: 'esm', minify: false,
});
if (!result.success) throw new Error('Could not bundle shared stock rules');
const output = result.outputs[0];
if (!output) throw new Error('No shared stock bundle');
await Bun.write('supabase/functions/_shared/social-market.generated.js', '// Generated by scripts/sync-stock-server.ts. Do not edit.\n' + await output.text());